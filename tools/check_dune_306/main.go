func checkAddr(session *gocql.Session, keyspace, addr string) (found bool, blockNum int64, txHash string, err error) {
	q := fmt.Sprintf("SELECT block_number, tx_hash FROM %s.contracts_by_address_v2 WHERE address=? LIMIT 1", keyspace)
	err = session.Query(q, "0x"+addr).Scan(&blockNum, &txHash)
	if err == gocql.ErrNotFound {
		return false, 0, "", nil
	}
	if err != nil {
		return false, 0, "", err
	}
	return true, blockNum, txHash, nil
}

func main() {
	host     := flag.String("host", "127.0.0.1", "Scylla host")
	port     := flag.Int("port", 9042, "Scylla port")
	user     := flag.String("user", "cassandra", "Scylla user")
	pass     := flag.String("pass", "", "Scylla password")
	keyspace := flag.String("keyspace", "eth", "Scylla keyspace")
	flag.Parse()

	if *pass == "" {
		log.Fatal("--pass required")
	}

	cluster := gocql.NewCluster(*host)
	cluster.Port = *port
	cluster.Authenticator = gocql.PasswordAuthenticator{Username: *user, Password: *pass}
	cluster.Keyspace = *keyspace
	cluster.Consistency = gocql.LocalQuorum
	cluster.Timeout = 30 * time.Second
	cluster.ConnectTimeout = 10 * time.Second
	cluster.NumConns = 4
	session, err := cluster.CreateSession()
	if err != nil {
		log.Fatalf("scylla connect: %v", err)
	}
	defer session.Close()

	log.Printf("Checking %d Dune-confirmed addresses in Scylla...", len(dune306))

	var (
		duneFound   int
		duneMissing int
		errors      int
	)

	fmt.Println("\n=== Dune-confirmed addresses (expect: all found) ===")
	for _, addr := range dune306 {
		found, blockNum, txHash, err := checkAddr(session, *keyspace, addr)
		if err != nil {
			log.Printf("[ERROR] 0x%s: %v", addr, err)
			errors++
			continue
		}
		if found {
			duneFound++
			fmt.Printf("[OK  ] 0x%s  block=%d tx=%s\n", addr, blockNum, txHash)
		} else {
			duneMissing++
			fmt.Printf("[MISS] 0x%s  — in Dune but NOT in our DB\n", addr)
		}
	}

	fmt.Println()
	fmt.Println("=== RESULT ===")
	fmt.Printf("Dune-confirmed (306):  found=%d  missing=%d\n", duneFound, duneMissing)
	fmt.Printf("errors: %d\n", errors)

	if duneMissing == 0 && errors == 0 {
		fmt.Println("\n✓ PASS: all 306 real contracts in DB")
	} else {
		fmt.Printf("\n✗ issues: %d Dune-confirmed missing from DB\n", duneMissing)
	}
}
